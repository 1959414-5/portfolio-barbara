-- Modelo relacional conceitual para PostgreSQL.
-- O app usa H2 em memória durante a demonstração local.
CREATE TABLE solicitacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    solicitante VARCHAR(100) NOT NULL,
    departamento VARCHAR(80) NOT NULL,
    prioridade VARCHAR(20) NOT NULL CHECK (prioridade IN ('BAIXA','MEDIA','ALTA','URGENTE')),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ABERTA','EM_ATENDIMENTO','RESOLVIDA','CANCELADA')),
    criada_em TIMESTAMP NOT NULL,
    atualizada_em TIMESTAMP NOT NULL
);

CREATE TABLE historico_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacoes(id),
    status_anterior VARCHAR(30),
    status_novo VARCHAR(30) NOT NULL,
    alterado_em TIMESTAMP NOT NULL,
    observacao VARCHAR(500)
);

CREATE INDEX idx_solicitacoes_status ON solicitacoes(status);
CREATE INDEX idx_historico_solicitacao ON historico_status(solicitacao_id, alterado_em DESC);

-- Exemplo analítico: contagem por status.
SELECT status, COUNT(*) AS total
FROM solicitacoes
GROUP BY status
ORDER BY total DESC;
